import re

class IngredientExtractor:
    def extract(self, text):
        """
        OCR 결과 텍스트에서 토큰 단위로 화장품 성분 키워드 조각이 포함되어 있는지 검사하여
        순수 전성분 데이터만 정확하게 추출해냅니다. (NER 방식)
        """
        # 1. '전성분' 키워드 추출 시도 (주의사항 전까지)
        match = re.search(r'(전\s*성\s*분|성\s*분|Ingredients?)\s*[:：]?\s*(.*)', text, re.IGNORECASE | re.DOTALL)
        if match:
            text = match.group(2)
            
        end_match = re.search(r'(사용\s*시\s*의?\s*주의\s*사항|주의\s*사항|사용\s*방법|How to use|용법\s*용량|효능\s*효과)', text, re.IGNORECASE)
        if end_match:
            text = text[:end_match.start()]

        # 2. 줄바꿈, 콤마, 마침표로 분리 (토큰화)
        raw_tokens = re.split(r'[,\n\.]+', text)
        
        # 화장품 성분에 자주 쓰이는 핵심 조각들 (OCR 오타 감안)
        core_substrings = [
            '정제수', '글리세', '추출', '주출', '글라이', '다이올', '디올', '아마이드', '파우더', 
            '펩타이드', '펩티드', '세라마이드', '폴리머', '플리머', '에스터', '왁스', '버터', '콜라겐', '엘라스틴', 
            '셀룰로', '실로로', '스테아', '솔베이트', '메티콘', '실록세인', '카보머', '올리베이트', 
            '글루코', '판테', '판놀', '알란토인', '베타인', '스쿠알란', '오일', '애씨드', '알코올', 
            '소듐', '소둡', '칼슘', '마그네', '징크', '티타늄', '산화', '여과', '용해', '단백질', 
            '비타민', '향료', '에탄올', '페녹시', '파라벤', '실리카', '마이카', '토코페', '헥산', '핵산',
            '아크릴', '아크럽', '메타', '라우', '팔미', '미리스', '설페이', '벤조', '실란',
            '우레아', '클로라이드', '브로마이드', '플루오', '피이지', '피피지', '시어', '망고', '코코',
            '아미노', '세테', '베헤', '비즈', '칸데릴', '카나우바', '스쿠알', '히알루', '히알', '나이아신',
            '레이트', '에이트', '미드', '산', '씨', '잎', '뿌리', '꽃', '열매', '발효'
        ]
        
        final_list = []
        
        for t in raw_tokens:
            t = t.strip()
            # 겉의 특수문자 제거
            t = re.sub(r'^[\'\"\-\+\*\@\:\;\·\(\)]+|[\'\"\-\+\*\@\:\;\·\(\)]+$', '', t).strip()
            
            if not t or len(t) < 2 or len(t) > 25:
                continue
            
            # 띄어쓰기가 3개 이상이면 문장으로 간주하고 버림
            if len(t.split()) > 3:
                continue
                
            # 마케팅/불필요 단어가 대놓고 포함되어 있다면 제외
            if re.search(r'(원한다면|선사|테스트|완료|기능성|화장품|상담실|이상이|공정거래|분쟁|보상해|사용방법|용량|효과|토너로|마스크|약\s*\d+분|떼어내고|맞추어|적당량|덜어|골고루|펴\s*바릅|사용|눈|주위|함유|보습|영양|피부|포뮬러|포물라|텍스처|녹아들어|제조업자|책임판매|판매업자|우수한|더해져|유지되는|부드럽게|자연스럽게|에멀전|크림|제품|유리|플라스틱|민감|탄력|트러블|리페어|제조원)', t):
                continue
                
            # 순수 영어나 숫자만 있는 경우 버림 (한국어 전성분 추출 목적)
            if re.match(r'^[a-zA-Z0-9\s\-\(\)\'\"]+$', t):
                continue
                
            # ★ 핵심 NER 매칭: 이 단어가 core_substrings 중 하나라도 포함하고 있는가?
            is_ingredient = any(sub in t for sub in core_substrings)
            
            if is_ingredient:
                final_list.append(t)
                
        if final_list:
            return ", ".join(final_list)
            
        return ""

